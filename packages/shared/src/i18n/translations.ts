/**
 * Get translated string by key and locale
 */
export function t(key: TranslationKey, locale: string = 'ru'): string {
  const translation = translations[key];
  if (!translation) return key;
  return translation[locale] || translation['en'] || translation['ru'] || key;
}

/**
 * Check if locale is supported
 */
export function isLocaleSupported(locale: string): boolean {
  // Check if any translation has this locale
  return Object.values(translations).some(t => locale in t);
}
