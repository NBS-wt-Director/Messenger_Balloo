// InstallService — сервис первичной установки Balloo
// Генерация .env, запуск миграций, seed, создание admin-аккаунта, установка флага .installed

import { execSync } from 'child_process';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { join } from 'path';
import { randomBytes } from 'crypto';
import bcrypt from 'bcryptjs';

const ROOT_DIR = join(__dirname, '../../..');
const ENV_PATH = join(ROOT_DIR, '.env');
const INSTALLED_FLAG_PATH = join(ROOT_DIR, '.installed');

// --- Типы ---
export interface InstallConfig {
  // Шаг 1: БД
  dbHost: string;
  dbPort: number;
  dbName: string;
  dbUser: string;
  dbPassword: string;

  // Шаг 2: Redis
  redisHost: string;
  redisPort: number;
  redisPassword: string;

  // Шаг 3: Домены
  domains: Record<string, string>;

  // Шаг 4: Ключи API
  yandexClientId: string;
  yandexClientSecret: string;
  vkClientId: string;
  vkClientSecret: string;
  mailruClientId: string;
  mailruClientSecret: string;
  yookassaShopId: string;
  yookassaApiKey: string;
  minioEndpoint: string;
  minioPort: number;
  minioAccessKey: string;
  minioSecretKey: string;
  minioBucket: string;
  smtpHost: string;
  smtpPort: number;
  smtpUser: string;
  smtpPassword: string;
  smtpFromEmail: string;
  smtpTls: string;
  pushPublicKey: string;
  pushPrivateKey: string;
  pushSubject: string;

  // Шаг 5: Безопасность
  jwtSecret: string;
  jwtAccessTtl: number;
  jwtRefreshTtl: number;
  setupPassword: string;
  adminInstallPassword: string;
}

// --- Проверка установленности ---
export function isInstalled(): boolean {
  return existsSync(INSTALLED_FLAG_PATH);
}

// --- Установка флага ---
export function markInstalled(): void {
  writeFileSync(INSTALLED_FLAG_PATH, new Date().toISOString());
}

