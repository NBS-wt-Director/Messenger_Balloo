// --- Тест подключения к БД ---
export function testDatabase(config: Pick<InstallConfig, 'dbHost' | 'dbPort' | 'dbName' | 'dbUser' | 'dbPassword'>): { ok: boolean; error?: string } {
  try {
    const url = `postgresql://${config.dbUser}:${encodeURIComponent(config.dbPassword)}@${config.dbHost}:${config.dbPort}/${config.dbName}?schema=public`;
    execSync(`npx prisma db pull --url "${url}"`, {
      cwd: join(ROOT_DIR, 'packages/shared'),
      timeout: 10000,
    });
    return { ok: true };
  } catch (err: any) {
    return { ok: false, error: err.stderr?.toString() || err.message || 'Unknown error' };
  }
}

// --- Тест подключения к Redis ---
export function testRedis(config: Pick<InstallConfig, 'redisHost' | 'redisPort' | 'redisPassword'>): { ok: boolean; error?: string } {
  try {
    const cmd = config.redisPassword
      ? `redis-cli -h ${config.redisHost} -p ${config.redisPort} -a ${config.redisPassword} ping`
      : `redis-cli -h ${config.redisHost} -p ${config.redisPort} ping`;
    const result = execSync(cmd, { timeout: 5000 }).toString().trim();
    return result === 'PONG' ? { ok: true } : { ok: false, error: `Redis returned: ${result}` };
  } catch (err: any) {
    return { ok: false, error: err.stderr?.toString() || err.message || 'Unknown error' };
  }
}

// --- Тест домена ---
export function testDomain(url: string): { ok: boolean; error?: string } {
  try {
    execSync(`curl -s -o /dev/null -w "%{http_code}" --connect-timeout 5 "${url}"`, { timeout: 10000 });
    return { ok: true };
  } catch {
    return { ok: false, error: `Cannot reach ${url}` };
  }
}

// --- Тест API ключа (заглушка — проверяет формат) ---
export function testApiKey(service: string, key: string): { ok: boolean; error?: string } {
  if (!key || key.length < 3) {
    return { ok: false, error: `Invalid ${service} key format` };
  }
  return { ok: true };
}

// --- Применение настроек ---
export function applyInstallConfig(config: InstallConfig): { ok: boolean; error?: string; steps: string[] } {
  const steps: string[] = [];

  try {
    // 1. Генерация .env
    generateEnvFile(config);
    steps.push('env_generated');

    // 2. Запуск миграций
    try {
      execSync('npx prisma migrate deploy', {
        cwd: join(ROOT_DIR, 'packages/shared'),
        timeout: 30000,
      });
      steps.push('migrations_applied');
    } catch (err: any) {
      steps.push('migrations_failed');
      // Небольшая задержка перед seed
    }

    // 3. Seed
    try {
      execSync('npx prisma db seed', {
        cwd: join(ROOT_DIR, 'packages/shared'),
        timeout: 30000,
      });
      steps.push('seed_applied');
    } catch {
      steps.push('seed_failed');
    }

    // 4. Создание admin-аккаунта (логика в контроллере)
    steps.push('admin_account_created');

    // 5. Установка флага
    markInstalled();
    steps.push('installed_flag_set');

    return { ok: true, steps };
  } catch (err: any) {
    steps.push('error');
    return { ok: false, error: err.stderr?.toString() || err.message || 'Unknown error', steps };
  }
}

// --- Перезапуск сервисов ---
export function restartServices(): { ok: boolean; error?: string } {
  try {
    // PM2
    if (existsSync(join(ROOT_DIR, 'pm2.json'))) {
      execSync('pm2 restart all', { timeout: 10000 });
      return { ok: true };
    }
    // Docker
    if (existsSync(join(ROOT_DIR, 'docker-compose.yml'))) {
      execSync('docker-compose restart', { timeout: 15000 });
      return { ok: true };
    }
    // systemd
    try {
      execSync('systemctl restart balloo-server', { timeout: 10000 });
      return { ok: true };
    } catch {
      return { ok: false, error: 'No supported service manager found (PM2/Docker/systemd)' };
    }
  } catch (err: any) {
    return { ok: false, error: err.stderr?.toString() || err.message || 'Restart failed' };
  }
}

// --- Генерация JWT secret ---
export function generateJwtSecret(): string {
  return randomBytes(64).toString('hex');
}

// --- Хеширование пароля — bcrypt (cost factor 12) ---
export function hashPassword(password: string): Promise<string> {
  return bcrypt.hash(password, 12);
}
