// --- Проверка установленности ---
export function isInstalled(): boolean {
  return existsSync(INSTALLED_FLAG_PATH);
}

// --- Установка флага ---
export function markInstalled(): void {
  writeFileSync(INSTALLED_FLAG_PATH, new Date().toISOString());
}

