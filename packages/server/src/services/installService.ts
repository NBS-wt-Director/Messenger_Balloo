  dbPort: number;
  dbName: string;
  dbUser: string;
  dbPassword: string;

  // Шаг 2: Redis
  redisHost: string;
  redisPort: number;
  redisPassword: string;

  // Шаг 3: Домены
  domains: Record<string, string>;

  // Шаг 4: Ключи API
  yandexClientId: string;
  yandexClientSecret: string;
  vkClientId: string;
  vkClientSecret: string;
  mailruClientId: string;
  mailruClientSecret: string;
  yookassaShopId: string;
  yookassaApiKey: string;
  yandexOsbucket: string;
  yandexOsAccessKey: string;
  yandexOsSecretKey: string;
  yandexOsEndpoint: string;
  minioEndpoint: string;
  minioPort: number;
  minioAccessKey: string;
  minioSecretKey: string;
  minioBucket: string;
  smtpHost: string;
  smtpPort: number;
  smtpUser: string;
  smtpPassword: string;
  smtpFromEmail: string;
  pushPublicKey: string;
  pushPrivateKey: string;
  pushSubject: string;
  grafanaUrl: string;
  grafanaAdminPassword: string;
  yandexMetricaCounterId: string;
  yandexMetricaToken: string;

